impl RuntimeFn {
    /// Whether every call from one task returns the same value without
    /// touching memory the caller sees, so a code generator may merge the
    /// calls. The frame stack keeps one address for a task's lifetime.
    pub(crate) fn is_task_invariant(self) -> bool {
        matches!(self, RuntimeFn::FrameStack)
    }
}

/// Where generated code finds the fields of a task's frame stack and a
/// frame descriptor's validation word. The runtime owns the layout, and
/// each executable checks the fingerprint at startup.
pub(crate) fn frame_stack_layout() -> aura_runtime::native_runtime::DirectFrameStackLayout {
    aura_runtime::native_runtime::direct_frame_stack_layout()
}

/// Where generated code finds a boxed value's reference counts and ledger
/// owner. The runtime owns the layout, and each executable checks the
/// fingerprint at startup.
pub(crate) fn ownership_layout() -> aura_runtime::native_runtime::DirectOwnershipLayout {
    aura_runtime::native_runtime::direct_ownership_layout()
}

/// The bytes of one frame stack entry.
pub(crate) const FRAME_STACK_ENTRY_BYTES: i64 =
    aura_runtime::native_runtime::DirectFrameStackLayout::ENTRY_BYTES;

/// One value per runtime helper, such as an emitter's declaration handle.
pub(crate) struct RuntimeTable<T>(Vec<T>);

impl<T> RuntimeTable<T> {
    pub(crate) fn try_build<E>(
        mut entry: impl FnMut(RuntimeFn) -> Result<T, E>,
    ) -> Result<Self, E> {
        RuntimeFn::ALL
            .iter()
            .map(|function| entry(*function))
            .collect::<Result<Vec<_>, _>>()
            .map(RuntimeTable)
    }

    pub(crate) fn map<U>(&self, entry: impl FnMut(&T) -> U) -> RuntimeTable<U> {
        RuntimeTable(self.0.iter().map(entry).collect())
    }

    /// Makes `function` resolve to `value` instead, and returns what it
    /// resolved to before.
    pub(crate) fn replace(&mut self, function: RuntimeFn, value: T) -> T {
        std::mem::replace(&mut self.0[function as usize], value)
    }
}

impl<T> Index<RuntimeFn> for RuntimeTable<T> {
    type Output = T;

    fn index(&self, function: RuntimeFn) -> &T {
        &self.0[function as usize]
    }
}

