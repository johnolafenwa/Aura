//! The direct runtime's C ABI as native code calls it. Each helper's symbol,
//! parameters, and result are declared once here for every emitter.

use std::ops::Index;

/// A machine word as the runtime ABI passes it.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub(crate) enum AbiType {
    I32,
    I64,
    F64,
}

macro_rules! runtime_functions {
    ($( $variant:ident => ($symbol:literal, [$($param:ident),* $(,)?], $result:expr) ),+ $(,)?) => {
        /// One helper exported by the direct runtime.
        #[derive(Clone, Copy, Debug, Eq, PartialEq, Hash, PartialOrd, Ord)]
        pub(crate) enum RuntimeFn {
            $($variant),+
        }

        impl RuntimeFn {
            /// Every helper, in declaration order.
            pub(crate) const ALL: &'static [RuntimeFn] = &[$(RuntimeFn::$variant),+];

            pub(crate) fn symbol(self) -> &'static str {
                match self {
                    $(RuntimeFn::$variant => $symbol),+
                }
            }

            pub(crate) fn params(self) -> &'static [AbiType] {
                match self {
                    $(RuntimeFn::$variant => &[$(AbiType::$param),*]),+
                }
            }

            pub(crate) fn result(self) -> Option<AbiType> {
                use AbiType::*;
                match self {
                    $(RuntimeFn::$variant => $result),+
                }
            }
        }
    };
}

